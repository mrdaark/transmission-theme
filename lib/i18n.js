export const languages = ['ru', 'en'];
let language = 'ru';
const pluralRules = { ru: new Intl.PluralRules('ru'), en: new Intl.PluralRules('en') };
const countedMessages = {
  '{count} файлов': {
    ru: { one: '{count} файл', few: '{count} файла', many: '{count} файлов', other: '{count} файла' },
    en: { one: '{count} file', other: '{count} files' },
  },
  '{count} пиров': {
    ru: { one: '{count} пир', few: '{count} пира', many: '{count} пиров', other: '{count} пира' },
    en: { one: '{count} peer', other: '{count} peers' },
  },
};
export const getLanguage = () => language;
export const getLocale = () => language === 'en' ? 'en-US' : 'ru-RU';
export function setLanguage(value) { language = languages.includes(value) ? value : 'ru'; }
export function tr(source, values = {}) {
  let message = language === 'en' ? english[source] ?? source : source;
  if (countedMessages[source] && Object.hasOwn(values, 'count')) {
    const forms = countedMessages[source][language];
    message = forms[pluralRules[language].select(Number(values.count))] ?? forms.other;
  }
  return message.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
}
export class LocalizedError extends Error {
  constructor(source, values = {}) { super(); this.source = source; this.values = values; }
  get message() { return tr(this.source, this.values); }
}
export function translateDocument(root = document) {
  root.documentElement.lang = getLanguage();
  for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = tr(element.getAttribute('data-i18n'));
  for (const attribute of ['aria-label', 'placeholder', 'title', 'content']) {
    for (const element of root.querySelectorAll(`[data-i18n-${attribute}]`)) element.setAttribute(attribute, tr(element.getAttribute(`data-i18n-${attribute}`)));
  }
}
